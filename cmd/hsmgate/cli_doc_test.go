package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"testing"
)

var updateCLIDoc = flag.Bool("update", false, "rewrite docs/cli.md from what the commands print")

// docs/cli.md is made from what the commands print for -h, so that it cannot say something else than the program does. `go test ./cmd/hsmgate -run CLIReference -update`
// rewrites it after a flag or a text changes; without -update the test fails when the file is not what the commands print.
func TestCLIReferenceIsCurrent(t *testing.T) {
	help := func(args ...string) string {
		cmd := exec.Command(os.Args[0], args...)
		cmd.Env = append(os.Environ(), "HSMGATE_RUN_MAIN=1")
		out, _ := cmd.CombinedOutput() // -h exits with 0 or 2: the text is what matters
		return strings.TrimRight(string(out), "\n")
	}
	var b strings.Builder
	b.WriteString(`# Command line reference

<!-- Generated by ` + "`go test ./cmd/hsmgate -run CLIReference -update`" + ` from what the commands print for -h: do not edit by hand. -->

One binary, several commands. This page is what ` + "`hsmgate <command> -h`" + ` prints. For what to do with them: [the README](../README.md), [operations.md](operations.md), [guides/clients.md](guides/clients.md).

## hsmgate

` + "```text\n" + help("help") + "\n```\n")
	sections := []struct {
		title, note string
		args        []string
	}{
		{"hsmgate dev", "Try it in a minute (see the README). Everything it makes is deleted when it stops, unless `-dir` is given.", []string{"dev", "-h"}},
		{"hsmgate serve", "", []string{"serve", "-h"}},
		{"hsmgate check", "", []string{"check", "-h"}},
		{"hsmgate unlock", "", []string{"unlock", "-h"}},
		{"hsmgate encrypt", "Environment variables stand in for the flags `-addr`, `-ca`, `-cert`, `-keyfile`, `-transit-key`, `-mount` (as `HSMGATE_ADDR`, ...). Several values at once, and Kubernetes Secrets: `-in-dir`, `-in-files`, `-k8s`.", []string{"encrypt", "-h"}},
		{"hsmgate decrypt", "", []string{"decrypt", "-h"}},
		{"hsmgate ca", "The commands that make certificates. `hsmgate ca` alone prints this; the flags below are shared by `setup`, `init`, `server`, `client` and `list` (each uses the ones its line above names).", []string{"ca"}},
		{"hsmgate ca: the flags", "", []string{"ca", "setup", "-h"}},
		{"hsmgate ping", "", []string{"ping", "-h"}},
	}
	for _, s := range sections {
		b.WriteString("\n## " + s.title + "\n\n")
		if s.note != "" {
			b.WriteString(s.note + "\n\n")
		}
		b.WriteString("```text\n" + help(s.args...) + "\n```\n")
	}
	b.WriteString("\n## hsmgate version\n\nPrints the version (`hsmgate v0.7.3`; `hsmgate dev` for a build from a clone).\n")
	want := b.String()
	if *updateCLIDoc {
		if err := os.WriteFile("../../docs/cli.md", []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("../../docs/cli.md")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Error(fmt.Sprint("docs/cli.md is not what the commands print: run `go test ./cmd/hsmgate -run CLIReference -update` and commit the file"))
	}
}
